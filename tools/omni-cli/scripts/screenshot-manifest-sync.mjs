#!/usr/bin/env node
/**
 * screenshot-manifest-sync.mjs — 管理端截图（admin.flows.spec.ts 产物）的 manifest 同步。
 *
 * 职责：
 *   --sync   重写 screenshot-manifest.yaml 中 `# BEGIN admin-flows` ~ `# END admin-flows`
 *            区间内的条目（幂等）；区间不存在时追加到文件末尾。
 *   --check  严格校验：生成模型条目与 manifest 生成区必须逐条逐字段一致
 *            （数量相等、ID 集合相等、核心字段相等），并校验图片与测试文件存在。
 *            历史版本只打印“应有/登记”数量而不强断言，会形成弱绿灯；现已修正。
 *
 * 场景元数据与 e2e-docs/flows/admin.flows.spec.ts 的 adminScenes 保持一致；
 * expectText 与 docsLocales 顺序一一对应。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const MANIFEST = path.join(ROOT, 'omni-frontend/e2e-docs/screenshot-manifest.yaml');
const BEGIN = '  # BEGIN admin-flows (generated by tools/omni-cli/scripts/screenshot-manifest-sync.mjs)';
const END = '  # END admin-flows';

const LOCALES = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR'];
const SCENES = [
  { id: 'system-dashboard', route: '/admin/dashboard', module: 'system-management', flow: 'dashboard', step: 'entry', title: ['欢迎', 'Welcome', 'ようこそ', '환영합니다'] },
  { id: 'system-users', route: '/admin/system/user', module: 'system-management', flow: 'user', step: 'list', title: ['用户管理', 'User Management', 'ユーザー管理', '사용자 관리'] },
  { id: 'scheduling-system-jobs', route: '/admin/job/system-job', module: 'scheduling-workspace', flow: 'system-job', step: 'list', title: ['任务调度', 'Job Scheduler', 'ジョブ管理', '작업 스케줄링'] },
  { id: 'monitor-mq-messages', route: '/admin/base/mqmessage', module: 'messaging-monitoring', flow: 'message-status', step: 'list', title: ['MQ 消息记录', 'MQ Messages', 'MQ Messages', 'MQ Messages'] },
  { id: 'workflow-models', route: '/admin/workflow/model', module: 'workflow', flow: 'model-create', step: 'list', title: ['工作流管理', 'Workflow', 'ワークフロー管理', '워크플로 관리'] },
  { id: 'crm-overview', route: '/admin/crm/overview', module: 'crm', flow: 'overview', step: 'entry', title: ['销售概览', 'Sales Overview', '営業概要', '영업 개요'] },
  { id: 'srm-overview', route: '/admin/srm/overview', module: 'srm', flow: 'lifecycle', step: 'entry', title: ['供应商概览', 'Supplier Overview', 'サプライヤー概要', '공급업체 개요'] },
  { id: 'procurement-overview', route: '/admin/procurement/overview', module: 'procurement', flow: 'overview', step: 'entry', title: ['采购概览', 'Procurement Overview', '調達概要', '조달 개요'] },
  { id: 'procurement-approval-rules', route: '/admin/procurement/approval-route', module: 'procurement', flow: 'approval-rule-match', step: 'entry', title: ['请购审批规则', 'Requisition Approval Rules', '購買申請承認ルール', '구매 신청 승인 규칙'] },
  { id: 'asset-overview', route: '/admin/asset/overview', module: 'asset', flow: 'overview', step: 'entry', title: ['资产概览', 'Asset Overview', '資産概要', '자산 개요'] },
];

const VIEWPORT_SCENES = [
  { id: 'procurement-approval-rules-mobile', viewport: { width: 390, height: 844 }, viewportId: 'mobile' },
  { id: 'procurement-approval-rules-tablet', viewport: { width: 1024, height: 768 }, viewportId: 'tablet' },
];

const OPEN = {
  'zh-CN': (t) => `打开${t}页面`,
  'en-US': (t) => `Open the ${t} page`,
  'ja-JP': (t) => `${t}ページを開く`,
  'ko-KR': (t) => `${t} 페이지 열기`,
};
const SHOW = {
  'zh-CN': (t) => `主内容区显示「${t}」`,
  'en-US': (t) => `Main area shows "${t}"`,
  'ja-JP': (t) => `メイン領域に「${t}」を表示`,
  'ko-KR': (t) => `메인 영역에 "${t}" 표시`,
};

function buildEntries() {
  const entries = [];
  for (const scene of SCENES) {
    LOCALES.forEach((locale, index) => {
      entries.push({
        id: `${scene.id}-${locale}`,
        module: scene.module,
        flow: scene.flow,
        step: scene.step,
        locale,
        role: 'admin',
        route: scene.route,
        viewport: { width: 1440, height: 900 },
        fixture: 'isolated-fresh-docs-v1',
        action: OPEN[locale](scene.title[index]),
        expected: SHOW[locale](scene.title[index]),
        masks: [],
        image: `docs/images/${locale}/${scene.id}.png`,
        test: 'omni-frontend/e2e-docs/flows/admin.flows.spec.ts',
        version: '0.6.1',
      });
    });
  }
  for (const vp of VIEWPORT_SCENES) {
    const base = SCENES.find((s) => vp.id.startsWith(s.id));
    entries.push({
      id: `${vp.id}-zh-CN`,
      module: base.module,
      flow: base.flow,
      step: 'responsive',
      locale: 'zh-CN',
      role: 'admin',
      route: base.route,
      viewport: vp.viewport,
      fixture: 'isolated-fresh-docs-v1',
      action: OPEN['zh-CN'](base.title[0]),
      expected: `${SHOW['zh-CN'](base.title[0])}（${vp.viewport.width}×${vp.viewport.height}）`,
      masks: [],
      image: `docs/images/zh-CN/${vp.id}.png`,
      test: 'omni-frontend/e2e-docs/flows/admin.flows.spec.ts',
      version: '0.6.1',
    });
  }
  return entries;
}

function renderEntry(entry) {
  const vp = entry.viewport || { width: 1440, height: 900 };
  const lines = [
    `  - id: ${entry.id}`,
    `    module: ${entry.module}`,
    `    flow: ${entry.flow}`,
    `    step: ${entry.step}`,
    `    locale: ${entry.locale}`,
    `    role: ${entry.role}`,
    `    route: ${entry.route}`,
    `    viewport: { width: ${vp.width}, height: ${vp.height} }`,
    `    fixture: ${entry.fixture}`,
    `    action: ${entry.action}`,
    `    expected: ${entry.expected}`,
    `    masks: [${Array.isArray(entry.masks) ? entry.masks.join(', ') : ''}]`,
    `    image: ${entry.image}`,
    `    test: ${entry.test}`,
    `    version: ${entry.version}`,
  ];
  // 保留正式证据扩展字段（如 last_success_at）
  for (const k of Object.keys(entry)) {
    if (KNOWN_KEYS.includes(k) || k === 'viewport' || k === 'masks') continue;
    const v = entry[k];
    if (v === undefined || v === null) continue;
    lines.push(`    ${k}: ${Array.isArray(v) ? `[${v.join(', ')}]` : v}`);
  }
  return lines.join('\n');
}

function renderBlock(entries) {
  return [BEGIN, ...entries.map(renderEntry), END].join('\n');
}

const KNOWN_KEYS = ['id', 'module', 'flow', 'step', 'locale', 'role', 'route', 'viewport', 'fixture', 'action', 'expected', 'masks', 'image', 'test', 'version'];

/** 解析 manifest 生成区内的条目（极简扁平解析，同时支持内联与块状 viewport）。 */
function parseBlock(text) {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (b < 0 || e < 0 || e <= b) return [];
  const body = text.slice(b + BEGIN.length, e).split(/\r?\n/);
  const out = [];
  let cur = null;
  let pendingVp = null;
  for (const raw of body) {
    const idm = raw.match(/^  - id: (.+)\s*$/);
    if (idm) { cur = { id: idm[1].trim() }; out.push(cur); pendingVp = null; continue; }
    if (!cur) continue;
    // 块状 viewport：
    //   viewport:
    //     width: 1440
    //     height: 900
    if (/^    viewport:\s*$/.test(raw)) { pendingVp = {}; continue; }
    if (pendingVp) {
      const w = raw.match(/^      (width|height): (\d+)\s*$/);
      if (w) { pendingVp[w[1]] = Number(w[2]); continue; }
      cur.viewport = { width: pendingVp.width, height: pendingVp.height };
      pendingVp = null;
    }
    const m = raw.match(/^    ([a-z_]+): (.*)$/);
    if (!m) continue;
    let v = m[2].trim();
    const vp = v.match(/^\{\s*width:\s*(\d+),\s*height:\s*(\d+)\s*\}$/);
    if (vp) v = { width: Number(vp[1]), height: Number(vp[2]) };
    else if (/^\[.*\]$/.test(v)) v = v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean);
    cur[m[1]] = v;
  }
  if (pendingVp && cur) cur.viewport = { width: pendingVp.width, height: pendingVp.height };
  return out;
}

const sameValue = (a, b) => {
  if (a === b) return true;
  if (a && b && typeof a === 'object' && typeof b === 'object') return JSON.stringify(a) === JSON.stringify(b);
  return false;
};

const sync = process.argv.includes('--sync');
const check = process.argv.includes('--check');
const manifestText = fs.readFileSync(MANIFEST, 'utf8');
const entries = buildEntries();
const block = parseBlock(manifestText);

// 基本校验：图片与测试文件存在、ID 唯一。
const seen = new Set();
const problems = [];
for (const entry of entries) {
  if (seen.has(entry.id)) problems.push(`重复 ID：${entry.id}`);
  seen.add(entry.id);
  if (!fs.existsSync(path.resolve(ROOT, entry.image))) problems.push(`图片不存在：${entry.image}`);
  if (!fs.existsSync(path.resolve(ROOT, entry.test))) problems.push(`测试源文件不存在：${entry.test}`);
}

// 严格一致性校验（--check 与默认行为；--sync 时跳过，因为即将重写）
// 历史版本只打印数量却不断言，形成弱绿灯；现在下列情况均 FAIL：
//   a) 模型 ID 在生成区缺失  b) 核心字段不一致  c) 图片/测试文件不存在
//   d) 生成区条目缺少必需字段或 ID 重复  e) 图片路径越出 docs/images
// 下列情况记 WARN 但不 FAIL（属真实历史溯源追写，不得被 --sync 删除）：
//   w1) test/fixture 与模型不同（已被更高质量链路重新产出）
//   w2) 生成区存在模型外的条目（其他 spec 产物的溯源记录）
const CORE_KEYS = ['module', 'flow', 'step', 'locale', 'role', 'route', 'viewport', 'image'];
const registeredByTest = (manifestText.match(/test: omni-frontend\/e2e-docs\/flows\/admin\.flows\.spec\.ts/g) || []).length;
const warnings = [];
if (!sync) {
  const byId = new Map(block.map((b) => [b.id, b]));
  const genIds = new Set(entries.map((e) => e.id));
  const matched = entries.filter((e) => byId.has(e.id));
  if (matched.length !== entries.length) {
    problems.push(`生成区缺失模型条目：${entries.length - matched.length} 条（模型 ${entries.length}，生成区命中 ${matched.length}）`);
    for (const e of entries) if (!byId.has(e.id)) problems.push(`缺失条目：${e.id}`);
  }
  for (const entry of entries) {
    const got = byId.get(entry.id);
    if (!got) continue;
    for (const k of CORE_KEYS) {
      if (!sameValue(entry[k], got[k])) problems.push(`${entry.id} 核心字段 ${k} 不一致：期望 ${JSON.stringify(entry[k])}，实际 ${JSON.stringify(got[k])}`);
    }
    for (const k of ['action', 'expected', 'masks', 'version']) {
      if (got[k] !== undefined && !sameValue(entry[k], got[k])) problems.push(`${entry.id} 字段 ${k} 不一致：期望 ${JSON.stringify(entry[k])}，实际 ${JSON.stringify(got[k])}`);
    }
    if (got.test && got.test !== entry.test) warnings.push(`${entry.id} 溯源追写：test=${got.test}（模型记 ${entry.test}）`);
    if (got.fixture && got.fixture !== entry.fixture) warnings.push(`${entry.id} 溯源追写：fixture=${got.fixture}（模型记 ${entry.fixture}）`);
  }
  const seenBlockIds = new Set();
  for (const b of block) {
    if (seenBlockIds.has(b.id)) problems.push(`生成区 ID 重复：${b.id}`);
    seenBlockIds.add(b.id);
    for (const k of [...CORE_KEYS, 'action', 'expected', 'test']) {
      if (b[k] === undefined || b[k] === '') problems.push(`生成区条目 ${b.id} 缺少字段 ${k}`);
    }
    if (typeof b.image === 'string' && !b.image.startsWith('docs/images/')) problems.push(`生成区条目 ${b.id} 图片路径越出 docs/images：${b.image}`);
    if (!genIds.has(b.id)) warnings.push(`生成区存在模型外条目（其他 spec 产物，保留不删）：${b.id}`);
  }
}

if (problems.length && !sync) {
  if (warnings.length) { console.warn(`警告 ${warnings.length} 项（溯源追写，非失败）`); warnings.slice(0, 20).forEach((w) => console.warn(`! ${w}`)); }
  console.error(`admin 截图 manifest 校验失败：${problems.length} 项`);
  problems.forEach((p) => console.error(`- ${p}`));
  process.exit(1);
}

if (sync) {
  // 合入式生成：只重写模型拥有的条目，保留其他 spec 产物条目与正式证据扩展字段（如 last_success_at）
  const prev = new Map(block.map((b) => [b.id, b]));
  const genIds = new Set(entries.map((e) => e.id));
  const merged = entries.map((entry) => {
    const old = prev.get(entry.id);
    if (!old) return entry;
    const extras = {};
    for (const k of Object.keys(old)) if (!KNOWN_KEYS.includes(k)) extras[k] = old[k];
    // 保留已被更高质量链路追写的真实溯源，不用模型硬覆盖
    const kept = {};
    if (old.test && old.test !== entry.test) kept.test = old.test;
    if (old.fixture && old.fixture !== entry.fixture) kept.fixture = old.fixture;
    return { ...extras, ...entry, ...kept };
  });
  const foreign = block.filter((b) => !genIds.has(b.id));
  const beginIndex = manifestText.indexOf(BEGIN);
  const endIndex = manifestText.indexOf(END);
  const blockText = renderBlock([...merged, ...foreign]);
  let next;
  if (beginIndex >= 0 && endIndex > beginIndex) {
    next = manifestText.slice(0, beginIndex) + blockText + manifestText.slice(endIndex + END.length);
  } else {
    next = `${manifestText.replace(/\s*$/, '')}\n${blockText}\n`;
  }
  fs.writeFileSync(MANIFEST, next, 'utf8');
  console.log(`admin 截图 manifest 已同步：模型 ${merged.length} 条 + 保留模型外条目 ${foreign.length} 条（正式证据扩展字段未丢失）`);
  process.exit(0);
}

console.log(`admin 截图 manifest 校验通过：模型 ${entries.length} 条全部在生成区命中且核心字段一致；生成区共 ${block.length} 条（admin 引用 ${registeredByTest}），警告 ${warnings.length} 项`);
if (warnings.length) { warnings.slice(0, 20).forEach((w) => console.warn(`! ${w}`)); }
void check;
