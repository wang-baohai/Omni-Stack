#!/usr/bin/env node
/**
 * screenshot-manifest-sync.mjs — 管理端截图（admin.flows.spec.ts 产物）的 manifest 同步。
 *
 * 职责：
 *   --sync   重写 screenshot-manifest.yaml 中 `# BEGIN admin-flows` ~ `# END admin-flows`
 *            区间内的条目（幂等）；区间不存在时追加到文件末尾。
 *   --check  校验区间条目的图片/测试文件存在、ID 无重复（默认行为）。
 *
 * 场景元数据与 e2e-docs/flows/admin.flows.spec.ts 的 adminScenes 保持一致；
 * expectText 与 docsLocales 顺序一一对应。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const MANIFEST = path.join(ROOT, 'omni-frontend/e2e-docs/screenshot-manifest.yaml');
const BEGIN = '  # BEGIN admin-flows (generated by tools/omni-cli/scripts/screenshot-manifest-sync.mjs)';
const END = '  # END admin-flows';

const LOCALES = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR'];
const SCENES = [
  { id: 'system-dashboard', route: '/admin/dashboard', module: 'system-management', flow: 'dashboard', step: 'entry', title: ['欢迎', 'Welcome', 'ようこそ', '환영합니다'] },
  { id: 'system-users', route: '/admin/system/user', module: 'system-management', flow: 'user', step: 'list', title: ['用户管理', 'User Management', 'ユーザー管理', '사용자 관리'] },
  { id: 'scheduling-system-jobs', route: '/admin/job/system-job', module: 'scheduling-workspace', flow: 'system-job', step: 'list', title: ['任务调度', 'Job Scheduler', 'ジョブ管理', '작업 스케줄링'] },
  { id: 'monitor-mq-messages', route: '/admin/base/mqmessage', module: 'messaging-monitoring', flow: 'message-status', step: 'list', title: ['MQ 消息记录', 'MQ Messages', 'MQ Messages', 'MQ Messages'] },
  { id: 'workflow-models', route: '/admin/workflow/model', module: 'workflow', flow: 'model-create', step: 'list', title: ['工作流管理', 'Workflow', 'ワークフロー管理', '워크플로 관리'] },
  { id: 'crm-overview', route: '/admin/crm/overview', module: 'crm', flow: 'overview', step: 'entry', title: ['销售概览', 'Sales Overview', '営業概要', '영업 개요'] },
  { id: 'srm-overview', route: '/admin/srm/overview', module: 'srm', flow: 'lifecycle', step: 'entry', title: ['供应商概览', 'Supplier Overview', 'サプライヤー概要', '공급업체 개요'] },
  { id: 'procurement-overview', route: '/admin/procurement/overview', module: 'procurement', flow: 'overview', step: 'entry', title: ['采购概览', 'Procurement Overview', '調達概要', '조달 개요'] },
  { id: 'procurement-approval-rules', route: '/admin/procurement/approval-route', module: 'procurement', flow: 'approval-rule-match', step: 'entry', title: ['请购审批规则', 'Requisition Approval Rules', '購買申請承認ルール', '구매 신청 승인 규칙'] },
  { id: 'asset-overview', route: '/admin/asset/overview', module: 'asset', flow: 'overview', step: 'entry', title: ['资产概览', 'Asset Overview', '資産概要', '자산 개요'] },
];

const VIEWPORT_SCENES = [
  { id: 'procurement-approval-rules-mobile', viewport: { width: 390, height: 844 }, viewportId: 'mobile' },
  { id: 'procurement-approval-rules-tablet', viewport: { width: 1024, height: 768 }, viewportId: 'tablet' },
];

const OPEN = {
  'zh-CN': (t) => `打开${t}页面`,
  'en-US': (t) => `Open the ${t} page`,
  'ja-JP': (t) => `${t}ページを開く`,
  'ko-KR': (t) => `${t} 페이지 열기`,
};
const SHOW = {
  'zh-CN': (t) => `主内容区显示「${t}」`,
  'en-US': (t) => `Main area shows "${t}"`,
  'ja-JP': (t) => `メイン領域に「${t}」を表示`,
  'ko-KR': (t) => `메인 영역에 "${t}" 표시`,
};

function buildEntries() {
  const entries = [];
  for (const scene of SCENES) {
    LOCALES.forEach((locale, index) => {
      entries.push({
        id: `${scene.id}-${locale}`,
        module: scene.module,
        flow: scene.flow,
        step: scene.step,
        locale,
        role: 'admin',
        route: scene.route,
        viewport: { width: 1440, height: 900 },
        fixture: 'isolated-fresh-docs-v1',
        action: OPEN[locale](scene.title[index]),
        expected: SHOW[locale](scene.title[index]),
        masks: [],
        image: `docs/images/${locale}/${scene.id}.png`,
        test: 'omni-frontend/e2e-docs/flows/admin.flows.spec.ts',
        version: '0.6.1',
      });
    });
  }
  for (const vp of VIEWPORT_SCENES) {
    const base = SCENES.find((s) => vp.id.startsWith(s.id));
    entries.push({
      id: `${vp.id}-zh-CN`,
      module: base.module,
      flow: base.flow,
      step: 'responsive',
      locale: 'zh-CN',
      role: 'admin',
      route: base.route,
      viewport: vp.viewport,
      fixture: 'isolated-fresh-docs-v1',
      action: OPEN['zh-CN'](base.title[0]),
      expected: `${SHOW['zh-CN'](base.title[0])}（${vp.viewport.width}×${vp.viewport.height}）`,
      masks: [],
      image: `docs/images/zh-CN/${vp.id}.png`,
      test: 'omni-frontend/e2e-docs/flows/admin.flows.spec.ts',
      version: '0.6.1',
    });
  }
  return entries;
}

function renderEntry(entry) {
  const lines = [
    `  - id: ${entry.id}`,
    `    module: ${entry.module}`,
    `    flow: ${entry.flow}`,
    `    step: ${entry.step}`,
    `    locale: ${entry.locale}`,
    `    role: ${entry.role}`,
    `    route: ${entry.route}`,
    `    viewport: { width: ${entry.viewport.width}, height: ${entry.viewport.height} }`,
    `    fixture: ${entry.fixture}`,
    `    action: ${entry.action}`,
    `    expected: ${entry.expected}`,
    `    masks: [${entry.masks.join(', ')}]`,
    `    image: ${entry.image}`,
    `    test: ${entry.test}`,
    `    version: ${entry.version}`,
  ];
  return lines.join('\n');
}

function renderBlock(entries) {
  return [BEGIN, ...entries.map(renderEntry), END].join('\n');
}

const sync = process.argv.includes('--sync');
const manifestText = fs.readFileSync(MANIFEST, 'utf8');
const entries = buildEntries();

// 基本校验：图片与测试文件存在、ID 唯一。
const seen = new Set();
const problems = [];
for (const entry of entries) {
  if (seen.has(entry.id)) problems.push(`重复 ID：${entry.id}`);
  seen.add(entry.id);
  if (!fs.existsSync(path.resolve(ROOT, entry.image))) problems.push(`图片不存在：${entry.image}`);
}
if (problems.length && !sync) {
  console.error(`admin 截图 manifest 校验失败：${problems.length} 项`);
  problems.forEach((p) => console.error(`- ${p}`));
  process.exit(1);
}

if (sync) {
  const beginIndex = manifestText.indexOf(BEGIN);
  const endIndex = manifestText.indexOf(END);
  const block = renderBlock(entries);
  let next;
  if (beginIndex >= 0 && endIndex > beginIndex) {
    next = manifestText.slice(0, beginIndex) + block + manifestText.slice(endIndex + END.length);
  } else {
    next = `${manifestText.replace(/\s*$/, '')}\n${block}\n`;
  }
  fs.writeFileSync(MANIFEST, next, 'utf8');
  console.log(`admin 截图 manifest 已同步：${entries.length} 条`);
  process.exit(0);
}

if (problems.length) {
  console.error(`admin 截图 manifest 校验失败：${problems.length} 项`);
  problems.forEach((p) => console.error(`- ${p}`));
  process.exit(1);
}
const registered = (manifestText.match(/test: omni-frontend\/e2e-docs\/flows\/admin\.flows\.spec\.ts/g) || []).length;
console.log(`admin 截图 manifest 校验通过：应登记 ${entries.length} 条，当前登记 ${registered} 条`);
